"""
503. The Time-Series Analytics Dashboard
----------------------------------------
Pipeline:
  1. Extract timestamps from an SQLite database
  2. Normalize (slice) timestamps to date only
  3. Aggregate with a dictionary
  4. Sort chronologically
  5. Export gline.js and open gline.html (D3.js zoomable line chart)

Only standard-library modules are used: sqlite3, datetime, random, os, webbrowser.
Run:  python time_series_engine.py
"""

import os
import random
import sqlite3
import webbrowser
from datetime import datetime, timedelta

DB_FILE = "logs.sqlite"
JS_FILE = "gline.js"
HTML_FILE = "gline.html"
RECORDS = 25000
START_DATE = datetime(2025, 1, 1)
DAYS = 365


# ---------------------------------------------------------------- sample data
def create_sample_database():
    """Create logs.sqlite with 25,000 random timestamps in 2025 (with spikes)."""
    random.seed(503)
    # Weight each day so the chart shows weekly rhythm, growth, and spikes
    days = [START_DATE + timedelta(days=i) for i in range(DAYS)]
    weights = []
    for i, d in enumerate(days):
        w = 1 + i / 150                      # slow upward trend
        if d.weekday() >= 5:                 # quieter weekends
            w *= 0.6
        weights.append(w)
    for spike_day, boost in ((331, 14), (180, 6), (59, 5)):  # e.g. Black Friday
        weights[spike_day] *= boost

    conn = sqlite3.connect(DB_FILE)
    cur = conn.cursor()
    cur.execute("DROP TABLE IF EXISTS Logs")
    cur.execute("CREATE TABLE Logs (id INTEGER PRIMARY KEY, timestamp TEXT)")
    chosen = random.choices(days, weights=weights, k=RECORDS)
    rows = []
    for d in chosen:
        t = d + timedelta(hours=random.randint(0, 23),
                          minutes=random.randint(0, 59),
                          seconds=random.randint(0, 59))
        rows.append((t.strftime("%Y-%m-%d %H:%M:%S"),))
    cur.executemany("INSERT INTO Logs (timestamp) VALUES (?)", rows)
    conn.commit()
    conn.close()


# ------------------------------------------------------------------ pipeline
def extract_and_aggregate(db_file):
    """Steps 1-3: read timestamps, slice to date, count in a dictionary."""
    conn = sqlite3.connect(db_file)
    cur = conn.cursor()
    counts = {}
    total = 0
    for row in cur.execute("SELECT timestamp FROM Logs"):
        if row[0] is None:
            continue
        date_only = str(row[0])[:10]                 # "2026-03-03 11:42:46" -> "2026-03-03"
        counts[date_only] = counts.get(date_only, 0) + 1
        total += 1
    conn.close()
    return counts, total


def fill_missing_days(counts, sorted_dates):
    """Add zero-count days between first and last date so the timeline has no gaps."""
    first = datetime.strptime(sorted_dates[0], "%Y-%m-%d")
    last = datetime.strptime(sorted_dates[-1], "%Y-%m-%d")
    filled = []
    day = first
    while day <= last:
        key = day.strftime("%Y-%m-%d")
        filled.append((key, counts.get(key, 0)))
        day += timedelta(days=1)
    return filled


def write_js(series, js_file):
    """Step 5: serialize Python data into a JavaScript array."""
    with open(js_file, "w") as f:
        f.write("// Auto-generated by time_series_engine.py\n")
        f.write("var timeSeriesData = [\n")
        lines = ['  {date: "%s", count: %d}' % (d, c) for d, c in series]
        f.write(",\n".join(lines))
        f.write("\n];\n")


def main():
    print("--- TIME-SERIES ENGINE START ---")

    if not os.path.exists(DB_FILE):
        print(f"No database found. Creating sample '{DB_FILE}'...")
        create_sample_database()

    counts, total = extract_and_aggregate(DB_FILE)
    if not counts:
        print("No timestamped records found. Nothing to plot.")
        return
    print(f"Extracting {total:,} timestamped records...")

    sorted_dates = sorted(counts.keys())             # chronological order
    series = fill_missing_days(counts, sorted_dates)
    print(f"Grouping data into {len(series)} daily buckets.")

    first_date, first_count = series[0]
    last_date, last_count = series[-1]
    peak_date, peak_count = max(series, key=lambda item: item[1])
    print(f"[LOG] First Date: {first_date} ({first_count:,} entries)")
    print(f"[LOG] Peak Activity: {peak_date} ({peak_count:,} entries)")
    print(f"[LOG] Last Date: {last_date} ({last_count:,} entries)")

    print("--- VISUALIZATION COMPLETE ---")
    write_js(series, JS_FILE)
    print(f"Timeline generated with {len(series)} data points.")
    print(f"Output saved to: {JS_FILE}")

    if os.path.exists(HTML_FILE):
        print(f"Opening '{HTML_FILE}' in browser...")
        webbrowser.open("file://" + os.path.abspath(HTML_FILE))
    else:
        print(f"'{HTML_FILE}' not found next to the script.")


if __name__ == "__main__":
    main()
